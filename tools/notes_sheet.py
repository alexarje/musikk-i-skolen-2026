#!/usr/bin/env python3
"""Writes ../notes.md, the speaker notes of every slide in index.html in order, with the slide's
address, its depth and its headline or caption, so the sheet is generated from the deck and never
edited by hand. Run from presentation/:  python tools/notes_sheet.py
"""
import html, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
PRES = os.path.dirname(HERE)
OUT = os.path.join(os.path.dirname(PRES), "notes.md")

# The numbers the deck fills in at load time, from images/numbers.js (written by make_figures.py).
_nj = os.path.join(PRES, "images", "numbers.js")
_js = open(_nj, encoding="utf8").read() if os.path.exists(_nj) else "{}"
NUMBERS = json.loads(_js[_js.index("{"):_js.rindex("}") + 1])

def strip(s):
    s = re.sub(r'<span data-n="(\w+)"></span>', lambda m: str(NUMBERS.get(m.group(1), "[missing %s]" % m.group(1))), s)
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()

def main():
    src = open(os.path.join(PRES, "index.html"), encoding="utf8").read()
    slides = src.split('<div class="slides">')[1].split("</div>\n</div>")[0]
    strips = re.split(r"\n<section>\n", slides)[1:]
    title = strip(re.search(r"<title>(.*?)</title>", src).group(1))
    lines = [f"# Speaker notes: {title}", "", "Generated by `presentation/tools/notes_sheet.py` from `presentation/index.html`. The address is `#/h/v`; the depth is basics unless the slide says more or deeper. Press S in the deck for the same notes beside the slide.", ""]
    n = 0
    for h, block in enumerate(strips):
        secs = re.findall(r"^  <section(.*?)^  </section>", block, re.M | re.S)
        for v, sec in enumerate(secs):
            depth = re.search(r'data-depth="(\w+)"', sec)
            depth = depth.group(1) if depth else "basics"
            head = re.search(r"<h1>(.*?)</h1>|<h2[^>]*>(.*?)</h2>|<p class=\"q\">(.*?)</p>|<p class=\"big\">(.*?)</p>|<p class=\"huge\"[^>]*>(.*?)<small>|<p class=\"kicker\">(.*?)</p>", sec, re.S)
            head = strip(next(g for g in head.groups() if g)) if head else "(figure)"
            notes = re.search(r'<aside class="notes">(.*?)</aside>', sec, re.S)
            notes = strip(notes.group(1)) if notes else "(no notes)"
            lines += [f"## {h}/{v} · {head}", "", f"*{depth}*", "", notes, ""]
            n += 1
    open(OUT, "w", encoding="utf8").write("\n".join(lines))
    print("wrote", OUT, n, "slides")

if __name__ == "__main__":
    main()
